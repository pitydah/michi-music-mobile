/**
 * ME-19: real, decodable FLAC generated by FFmpeg, then independently verified
 * with ffprobe/metaflac. The production save must preserve the encoded audio
 * frame region byte-for-byte while publishing text, pairs and multivalue.
 */
@RunWith(AndroidJUnit4::class)
class MetadataSaveFlacAdvancedInstrumentedTest {
    private lateinit var context: Context
    private lateinit var database: MichiDatabase
    private lateinit var journalRoot: File
    private var created: Uri? = null
    private var trackId = ""
    private val sourceId = MichiDatabase.DEFAULT_DEVICE_LIBRARY_ID

    @Before fun setup() {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        context = instrumentation.targetContext
        database = Room.inMemoryDatabaseBuilder(context, MichiDatabase::class.java)
            .allowMainThreadQueries().build()
        journalRoot = File(context.noBackupFilesDir, "michi-metadata-editor-v1")
        journalRoot.deleteRecursively()
    }

    @After fun cleanup() {
        created?.let { runCatching { context.contentResolver.delete(it, null, null) } }
        database.close()
        journalRoot.deleteRecursively()
    }

    private fun fixture(): ByteArray =
        InstrumentationRegistry.getInstrumentation().context.assets
            .open("me19-sine.flac").use { it.readBytes() }

    @Test fun advancedTextAndPairsPreserveRealFlacAudioFrames() = runBlocking {
        val original = fixture()
        val uri = insert(original)
        seedRow(original)
        val review = MetadataEditPreview.review(
            coldRead(uri, original.size.toLong()),
            listOf(
                MetadataChange.Replace(MetadataField.TITLE, listOf("ME19 FLAC Nuevo")),
                MetadataChange.Replace(MetadataField.ALBUM_ARTIST,
                    listOf("Artista de Album")),
                MetadataChange.Replace(MetadataField.COMPOSER,
                    listOf("Compositora Nueva")),
                MetadataChange.Replace(MetadataField.RELEASE_DATE, listOf("2025-11-25")),
                MetadataChange.Replace(MetadataField.TRACK_NUMBER, listOf("3")),
                MetadataChange.Replace(MetadataField.TRACK_TOTAL, listOf("12")),
                MetadataChange.Replace(MetadataField.DISC_NUMBER, listOf("1")),
                MetadataChange.Replace(MetadataField.DISC_TOTAL, listOf("2")),
                MetadataChange.Replace(MetadataField.COMMENT,
                    listOf("Comentario nuevo")),
                MetadataChange.Replace(MetadataField.LYRICS, listOf("Letra nueva")),
            ),
        ) as MetadataReview.Ready
        val outcome = MetadataSaveService(context, database.trackDao(), database).save(
            sourceId, trackId, uri.toString(), original.size.toLong(), review,
            ownerCurrent = { true }, playbackClosed = { true },
        )
        assertTrue("outcome=$outcome", outcome is MetadataSaveService.Outcome.Saved &&
            outcome.indexPublished)
        val after = context.contentResolver.openInputStream(uri)!!.use { it.readBytes() }
        assertFlacAudioFramesIdentical(original, after)
        val reopened = coldRead(uri, after.size.toLong())
        assertEquals(listOf("ME19 FLAC Nuevo"), reopened.known[MetadataField.TITLE])
        assertEquals(listOf("Artista de Album"),
            reopened.known[MetadataField.ALBUM_ARTIST])
        assertEquals(listOf("Compositora Nueva"),
            reopened.known[MetadataField.COMPOSER])
        assertEquals(listOf("2025-11-25"),
            reopened.known[MetadataField.RELEASE_DATE])
        assertEquals(listOf("3"), reopened.known[MetadataField.TRACK_NUMBER])
        assertEquals(listOf("12"), reopened.known[MetadataField.TRACK_TOTAL])
        assertEquals(listOf("1"), reopened.known[MetadataField.DISC_NUMBER])
        assertEquals(listOf("2"), reopened.known[MetadataField.DISC_TOTAL])
        assertEquals(listOf("Comentario nuevo"),
            reopened.known[MetadataField.COMMENT])
        assertEquals(listOf("Letra nueva"), reopened.known[MetadataField.LYRICS])
        val evidence = database.trackDao()
            .getCurrentExtendedTagEvidence(sourceId, trackId)
            ?: throw AssertionError("extended evidence must be published")
        assertEquals("Compositora Nueva", evidence.composer)
        assertEquals(3, evidence.trackNumber)
        assertEquals(12, evidence.trackTotal)
        assertEquals(1, evidence.discNumber)
        assertEquals(2, evidence.discTotal)
        assertEquals("2025-11-25", evidence.date)
        assertTrue(MetadataRecoveryJournalV1(journalRoot).inspect() is
            MetadataRecoveryJournalV1.Inspection.Clear)
    }

    @Test fun addAndRemoveRealFlacPicturePreservesEncodedAudio() = runBlocking {
        val original = fixture()
        val blue = InstrumentationRegistry.getInstrumentation().context.assets
            .open("me19-cover-blue.png").use { it.readBytes() }
        val uri = insert(original)
        seedRow(original)
        val observed = observeBytes(original)
        assertEquals(1, observed.artworks.size)
        val red = observed.artworks.single().image
        val target = coldRead(uri, original.size.toLong()).target
        val addition = (
            MetadataArtworkAdditionPreview.review(
                observed, blue, "image/png",
            ) as MetadataArtworkAdditionPreview.Result.Ready
            ).proposal
        val addOutcome = MetadataSaveService(context, database.trackDao(), database)
            .saveBundle(
                sourceId = sourceId, trackId = trackId, uriString = uri.toString(),
                expectedBytes = original.size.toLong(), targetInput = target,
                reviewInput = null,
                resourceEdits = listOf(
                    MetadataSelectiveAssetStage.Edit.PictureAdd(addition),
                ),
                ownerCurrent = { true }, playbackClosed = { true },
            )
        assertTrue("FLAC picture add must publish: $addOutcome",
            addOutcome is MetadataSaveService.Outcome.Saved &&
                addOutcome.indexPublished)
        val addSaved = addOutcome as MetadataSaveService.Outcome.Saved
        val afterAdd = context.contentResolver.openInputStream(uri)!!.use { it.readBytes() }
        assertFlacAudioFramesIdentical(original, afterAdd)
        val addedResources = observeBytes(afterAdd)
        assertEquals(2, addedResources.artworks.size)
        assertArrayEquals(red, addedResources.artworks[0].image)
        assertArrayEquals(blue, addedResources.artworks[1].image)
        assertEquals(setOf(MetadataResourceOperation.FLAC_PICTURE_ADD),
            checkNotNull(addSaved.libraryChange).resourceOperations)
        assertEquals(afterAdd.size.toLong(),
            checkNotNull(addSaved.libraryChange).committedBytes)

        val removeOutcome = MetadataSaveService(context, database.trackDao(), database)
            .saveBundle(
                sourceId = sourceId, trackId = trackId, uriString = uri.toString(),
                expectedBytes = afterAdd.size.toLong(), targetInput = addSaved.snapshot.target,
                reviewInput = null,
                resourceEdits = listOf(
                    MetadataSelectiveAssetStage.Edit.PictureRemove(
                        0, observed.artworks.single().info.sha256,
                    ),
                ),
                ownerCurrent = { true }, playbackClosed = { true },
            )
        assertTrue("FLAC picture remove must publish: $removeOutcome",
            removeOutcome is MetadataSaveService.Outcome.Saved &&
                removeOutcome.indexPublished)
        val removed = removeOutcome as MetadataSaveService.Outcome.Saved
        val afterRemove = context.contentResolver.openInputStream(uri)!!.use { it.readBytes() }
        assertFlacAudioFramesIdentical(original, afterRemove)
        val removedResources = observeBytes(afterRemove)
        assertEquals(1, removedResources.artworks.size)
        assertArrayEquals(blue, removedResources.artworks.single().image)
        assertEquals(setOf(MetadataResourceOperation.FLAC_PICTURE_REMOVE),
            checkNotNull(removed.libraryChange).resourceOperations)
        assertEquals(afterRemove.size.toLong(),
            checkNotNull(removed.libraryChange).committedBytes)
        assertTrue(MetadataRecoveryJournalV1(journalRoot).inspect() is
            MetadataRecoveryJournalV1.Inspection.Clear)
    }

    @Test fun orderedFlacArtistListReachesColdReadAndPersonEvidence() = runBlocking {        val original = fixture()
        val uri = insert(original)
        seedRow(original)
        val artists = listOf("Artista Uno", "Artista Dos", "Artista Tres")
        val review = MetadataEditPreview.review(
            coldRead(uri, original.size.toLong()),
            listOf(MetadataChange.Replace(MetadataField.ARTIST, artists)),
        ) as MetadataReview.Ready
        val outcome = MetadataSaveService(context, database.trackDao(), database).save(
            sourceId, trackId, uri.toString(), original.size.toLong(), review,
            ownerCurrent = { true }, playbackClosed = { true },
        )
        assertTrue("outcome=$outcome", outcome is MetadataSaveService.Outcome.Saved &&
            outcome.indexPublished)
        val after = context.contentResolver.openInputStream(uri)!!.use { it.readBytes() }
        assertFlacAudioFramesIdentical(original, after)
        val reopened = coldRead(uri, after.size.toLong())
        assertEquals(artists, reopened.known[MetadataField.ARTIST])
        val row = database.trackDao().getTrackBySource(sourceId, trackId)!!
        assertEquals(artists.first(), row.artist)
        val people = database.metadataPersonEvidenceDao()
            .currentForTrack(sourceId, trackId)
            ?: throw AssertionError("person evidence must be published")
        assertEquals(artists, people.artists())
        assertTrue(people.structurallyValid())
    }

    private fun observeBytes(bytes: ByteArray): MetadataArtworkLyricsProbe.Snapshot {
        val file = File(context.cacheDir, "me19-art-${UUID.randomUUID()}.flac")
        return try {
            file.writeBytes(bytes)
            MetadataPrivateBundleStage.observeFile(file)
        } finally { file.delete() }
    }

    private fun assertFlacAudioFramesIdentical(before: ByteArray, after: ByteArray) {
        val beforeOffset = flacAudioOffset(before)
        val afterOffset = flacAudioOffset(after)
        assertTrue("encoded audio must remain", after.size > afterOffset)
        assertArrayEquals(
            before.copyOfRange(beforeOffset, before.size),
            after.copyOfRange(afterOffset, after.size),
        )
    }

    private fun flacAudioOffset(bytes: ByteArray): Int {
        assertTrue("fLaC header", bytes.size > 4 &&
            String(bytes, 0, 4, StandardCharsets.US_ASCII) == "fLaC")
        var p = 4
        while (p + 4 <= bytes.size) {
            val header = bytes[p].toInt() and 255
            val last = header and 0x80 != 0
            val length = ((bytes[p + 1].toInt() and 255) shl 16) or
                ((bytes[p + 2].toInt() and 255) shl 8) or
                (bytes[p + 3].toInt() and 255)
            p += 4 + length
            if (last) return p
        }
        throw AssertionError("FLAC metadata has no last block")
    }

    private suspend fun insert(bytes: ByteArray): Uri {
        val values = ContentValues().apply {
            put(MediaStore.Audio.Media.DISPLAY_NAME,
                "me19-flac-${UUID.randomUUID()}.flac")
            put(MediaStore.Audio.Media.MIME_TYPE, "audio/flac")
            put(MediaStore.Audio.Media.RELATIVE_PATH, "Music/ME19Flac")
            put(MediaStore.Audio.Media.IS_PENDING, 1)
        }
        val uri = requireNotNull(context.contentResolver.insert(
            MediaStore.Audio.Media.getContentUri(MediaStore.VOLUME_EXTERNAL_PRIMARY), values))
        created = uri
        context.contentResolver.openFileDescriptor(uri, "rwt")!!.use { pfd ->
            ParcelFileDescriptor.AutoCloseOutputStream(pfd).use {
                it.write(bytes); it.flush(); it.fd.sync()
            }
        }
        values.clear()
        values.put(MediaStore.Audio.Media.IS_PENDING, 0)
        context.contentResolver.update(uri, values, null, null)
        trackId = "local_${uri.lastPathSegment!!.toLong()}"
        return uri
    }

    private suspend fun seedRow(bytes: ByteArray) {
        val repository = SyncedTrackRepository(trackDao = database.trackDao())
        repository.saveLibrary(listOf(TrackDto(
            id = trackId, title = "seed", artist = "", album = "",
            duration = 100, size = bytes.size.toLong(), format = "flac", genre = "",
        )), sourceId)
        repository.markDownloadedVerified(
            sourceId = sourceId, id = trackId, filepath = created.toString(),
            size = bytes.size.toLong(), sha256 = sha(bytes),
            verifiedAt = 1_700_000_000_000, algorithm = "sha256")
    }

    private suspend fun coldRead(uri: Uri, size: Long): MetadataSnapshot =
        when (val read = ExtendedTrackMetadataRepository(database.trackDao(), context)
            .loadEditorColdRead("", trackId, uri.toString(), size)) {
            is MetadataEditorColdRead.Verified -> read.snapshot
            is MetadataEditorColdRead.Partial -> read.snapshot
            else -> error("cold read failed: $read")
        }

    private fun sha(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes)
            .joinToString("") { "%02x".format(it.toInt() and 255) }
}
